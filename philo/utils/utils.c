#include "utils.h"

int	ft_atoi(const char *nptr)
{
	size_t	i;
	int	res;

	res = 0;
	i = 0;
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		res = res * 10 + nptr[i] - '0';
		i++;
	}
	return (res);
}
